def _in_streamlit() -> bool:
    """True when `streamlit run` is executing this file (streamlit is then already imported)."""
    if "streamlit" not in sys.modules:
        return False
    from streamlit.runtime.scriptrunner import get_script_run_ctx

    try:
        return get_script_run_ctx(suppress_warning=True) is not None
    except TypeError:  # older streamlit without suppress_warning
        return get_script_run_ctx() is not None


def _demo() -> int:
    """No arguments: train on first run, then a prediction and a simulation."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(levelname)-8s | %(message)s")
    engine = load_or_train(DEFAULT_MODEL_PATH)
    print("\n=== MATCH PREDICTION REPORT ===")
