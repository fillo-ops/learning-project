def _top_level_names(source: str) -> set[str]:
    names = set()
    for node in ast.parse(source).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def _script_body(name: str, body: str, docstring: str | None) -> str:
    """Turns a script into a `_cli_<name>(argv)` function."""
    func = f"_cli_{name}"
    body = body.replace("description=__doc__", f"description={docstring!r}")
    tree = ast.parse(body)
    main_guard = next(
        (n for n in tree.body if isinstance(n, ast.If) and "__main__" in ast.unparse(n.test)),
        None,
    )
    lines = body.splitlines()
    if any(isinstance(n, ast.FunctionDef) and n.name == "main" for n in tree.body):
        # Scripts with main(argv): rename it and drop the __main__ guard
        keep = [
            ln for i, ln in enumerate(lines) if not main_guard or not main_guard.lineno - 1 <= i < main_guard.end_lineno
        ]
        out = "\n".join(keep)
        return re.sub(r"^def main\(", f"def {func}(", out, flags=re.MULTILINE).rstrip()
    if main_guard is None:
        raise RuntimeError(f"scripts/{name}.py has neither main() nor a __main__ block")
    # Scripts that only have a __main__ block: wrap its body into a function
    guard_body = "\n".join(lines[main_guard.body[0].lineno - 1 : main_guard.end_lineno])
    guard_body = textwrap.dedent(guard_body).replace("parser.parse_args()", "parser.parse_args(argv)")
    before = "\n".join(lines[: main_guard.lineno - 1]).rstrip()
    wrapped = f"def {func}(argv: list[str] | None = None) -> int:\n{textwrap.indent(guard_body, '    ')}\n    return 0"
    return (before + "\n\n\n" + wrapped).strip()


def _indent_block(code: str) -> str:
    return textwrap.indent(code, "    ")


def build() -> str:
    hoisted: list[str] = []
    sections: list[str] = []
    seen_names: dict[str, str] = {}

    def register(source: str, label: str) -> None:
        for n in _top_level_names(source):
            if n in seen_names and n not in ALLOWED_DUPLICATES:
                raise RuntimeError(f"Name clash: {n!r} defined in {seen_names[n]} and {label}")
            seen_names.setdefault(n, label)

    for mod in _src_order():
        imports, body, doc = _split((ROOT / "src" / f"{mod}.py").read_text(), f"src/{mod}.py")
        if mod == "config":
            body = body.replace("Path(__file__).resolve().parent.parent", "Path(__file__).resolve().parent")
        if mod == "model":
            body = body.replace("engine = pickle.load(f)", "engine = _BundleUnpickler(f).load()")
            body = UNPICKLER + "\n\n\n" + body
        register(body, f"src/{mod}.py")
        hoisted += imports
        title = (doc or "").splitlines()[0] if doc else ""
        sections.append(_banner(f"src/{mod}.py", title) + body)

    for script in SCRIPTS:
        imports, body, doc = _split((ROOT / "scripts" / f"{script}.py").read_text(), f"scripts/{script}.py")
        body = _script_body(script, body, doc)
        register(body, f"scripts/{script}.py")
        hoisted += imports
        sections.append(_banner(f"scripts/{script}.py", "CLI subcommand") + body)

    # API: schemas and routes need fastapi / pydantic, which stay optional
    s_imports, schemas, _ = _split((ROOT / "api" / "schemas.py").read_text(), "api/schemas.py")
    m_imports, routes, _ = _split((ROOT / "api" / "main.py").read_text(), "api/main.py")
    # Streamlit >= 1.5x scans `streamlit run` targets for `x = FastAPI(...)` assignments and then serves the
    # file as an ASGI app instead of the dashboard, so the bundle builds the app through a helper.
    routes = routes.replace("app = FastAPI(", "app = _make_fastapi(")
    api_imports = [i for i in s_imports + m_imports if "fastapi" in i or "pydantic" in i]
    hoisted += [i for i in s_imports + m_imports if i not in api_imports]
    api = (
        "try:\n"
        + _indent_block("\n".join(dict.fromkeys(api_imports)))
        + "\nexcept ImportError:  # the API is optional; the rest of the system works without fastapi\n"
        + "    FastAPI = None\n\n"
        + "if FastAPI is not None:\n"
        + _indent_block(schemas)
        + "\n\n\ndef _make_fastapi(**kwargs):\n"
        + '    """Indirection so Streamlit does not mistake this file for an ASGI app (see build script)."""\n'
        + "    return FastAPI(**kwargs)\n"
        + "\n\ndef create_app():\n"
        + '    """Builds the FastAPI app (requires fastapi + uvicorn)."""\n'
        + "    if FastAPI is None:\n"
        + '        raise RuntimeError("pip install fastapi uvicorn to run the API")\n'
        + _indent_block(routes)
        + "\n    return app"
    )
    sections.append(_banner("api/schemas.py + api/main.py", "FastAPI service") + api)

    # Dashboard: the Streamlit script becomes a function
    d_imports, dash, _ = _split((ROOT / "app" / "dashboard.py").read_text(), "app/dashboard.py")
    dash = "\n".join(ln for ln in dash.splitlines() if "sys.path.insert" not in ln)
    st_imports = [i for i in d_imports if "streamlit" in i]
    hoisted += [i for i in d_imports if i not in st_imports and not i.startswith(("import sys", "from pathlib"))]
