def main(argv: list[str]) -> int:
    code = build()
    compile(code, str(OUTPUT), "exec")
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != code:
            print(f"{OUTPUT.name} is stale: run python tools/build_single_file.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_text(code)
    print(f"Wrote {OUTPUT.name} ({len(code.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
