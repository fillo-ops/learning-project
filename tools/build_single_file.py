def _order_imports(hoisted: list[str]) -> str:
    """Merges `from x import a` / `from x import b` into one line, then sorts stdlib before third-party."""
    plain: set[str] = set()
    from_imports: dict[str, set[str]] = {}
    for stmt in hoisted:
        for node in ast.parse(stmt).body:
            if isinstance(node, ast.ImportFrom):
                from_imports.setdefault(node.module, set()).update(
                    a.name if not a.asname else f"{a.name} as {a.asname}" for a in node.names
                )
            else:
                plain.add(ast.unparse(node))
    lines = list(plain) + [f"from {m} import {', '.join(sorted(n))}" for m, n in from_imports.items()]
    stdlib = sorted(i for i in lines if i.split()[1].split(".")[0] in sys.stdlib_module_names)
    third = sorted(i for i in lines if i not in stdlib)
    return "\n".join(stdlib) + "\n\n" + "\n".join(third)


def _banner(source: str, title: str) -> str:
    line = "# " + "=" * 78
    return f"{line}\n# {source}" + (f": {title}" if title else "") + f"\n{line}\n"


